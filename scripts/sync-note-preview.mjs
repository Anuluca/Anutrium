import less from 'less'
import assert from 'node:assert/strict'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// 以网站的渲染器和样式为单一来源，生成后台自包含文件；部署时不依赖相邻仓库。
const root = fileURLToPath(new URL('../', import.meta.url))
const consoleRoot = path.resolve(root, '../AnuConsole')
const destination = path.join(consoleRoot, 'src/lib/note-renderer')
const check = process.argv.includes('--check')
const output = async (file, data) => {
  if (check)
    assert.deepEqual(
      await readFile(file),
      Buffer.from(data),
      `后台预览文件未同步：${file}`
    )
  else await writeFile(file, data)
}
const copy = async (source, target) => output(target, await readFile(source))
await mkdir(destination, { recursive: true })
// 后台保持自包含，同时共用网站唯一的联系方式配置。
await output(
  path.join(destination, 'renderNoteMarkdown.ts'),
  (
    await readFile(path.join(root, 'src/utils/renderNoteMarkdown.ts'), 'utf8')
  ).replace('../locales/modules/contactLinks', './contactLinks')
)
await copy(
  path.join(root, 'src/locales/modules/contactLinks.ts'),
  path.join(destination, 'contactLinks.ts')
)
for (const file of [
  'noteWidgets.ts',
  'imageVariant.ts',
  'noteHexoTags.ts',
  'noteCodeLines.ts',
  'noteTooltip.ts',
  'noteEntrance.ts',
  'imageCincoHover.ts',
])
  await copy(path.join(root, 'src/utils', file), path.join(destination, file))
await copy(
  path.join(root, 'src/types/note-markdown-plugins.d.ts'),
  path.join(destination, 'plugins.d.ts')
)
const filename = path.join(root, 'src/views/Home/styles/noteReader.less')
const { css } = await less.render(await readFile(filename, 'utf8'), {
  filename,
})
await output(
  path.join(destination, 'noteReader.css'),
  '/* Generated by Anutrium scripts/sync-note-preview.mjs. */\n' + css
)
await mkdir(path.join(consoleRoot, 'public/fonts/notes'), { recursive: true })
for (const file of await readdir(path.join(root, 'public/fonts/notes')))
  await copy(
    path.join(root, 'public/fonts/notes', file),
    path.join(consoleRoot, 'public/fonts/notes', file)
  )
console.log(
  check
    ? '两端 Notes 渲染器、样式和字体一致。'
    : '已同步 Notes 渲染器、正文样式和原始字体到 AnuConsole。'
)
